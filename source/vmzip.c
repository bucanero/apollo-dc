int vmzip_name_ext(const char* name)
{
	const char* p = name + strlen(VMZIP_PREFIX);

	if (strncmp(name, VMZIP_PREFIX, strlen(VMZIP_PREFIX)) != 0 || strlen(p) != 3)
		return -1;

	for (int i = 0; i < 3; i++)
		if (p[i] < '0' || p[i] > '9')
			return -1;

	return (p[0] - '0') * 100 + (p[1] - '0') * 10 + (p[2] - '0');
}

int vmzip_is_vmzip(const char* name)
{
	return (vmzip_name_ext(name) >= 0);
}

// The original name: the VMU description's first 12 bytes. VMZip space pads
// it (old KOS builds NUL padded it): trailing padding isn't part of the name.
static int get_orig_name(const uint8_t* hdr, char* name)
{
	int n = VMU_NAME;

	memcpy(name, hdr + VMS_DESC_VMS, VMU_NAME);
	name[VMU_NAME] = 0;

	for (int i = 0; i < VMU_NAME; i++)
		if (!name[i])
		{
			n = i;
			break;
		}

	while (n > 0 && name[n - 1] == ' ')
		n--;
	name[n] = 0;

	for (int i = 0; i < n; i++)
		if ((uint8_t) name[i] < 0x20 || name[i] == '/')
			return 0;

	return (n > 0);
}

int vmzip_header_info(const uint8_t* hdr, size_t len, char* name, int* blocks)
{
	if (len < VMS_ICONS)
		return 0;

	// the app ID tells VMZip files apart (VMZip 1.0's or Apollo's); VMZip itself only went by the file name
	if (!hdr[VMS_APP_ID] ||
		(memcmp(hdr + VMS_APP_ID + 1, VMZIP_APP_ID_ORIG, strlen(VMZIP_APP_ID_ORIG)) != 0 &&
		 memcmp(hdr + VMS_APP_ID + 1, VMZIP_APP_ID, strlen(VMZIP_APP_ID) + 1) != 0))
		return 0;

	*blocks = hdr[VMS_APP_ID];
	return get_orig_name(hdr, name);
}

int vmzip_pack(const char* orig_name, const uint8_t* data, size_t len, uint8_t** out, size_t* out_len)
{
	size_t name_len = strlen(orig_name);
	unsigned int bz_len;
	uint8_t* buf;

	// the size byte holds up to 255 blocks (a VMU has 200)
	if (!len || len % VMU_BLOCK || len / VMU_BLOCK > 255 || !name_len || name_len > VMU_NAME)
		return 0;

	// bzip2's worst case: 1% bigger plus 600 bytes
	bz_len = len + len / 100 + 600;
	buf = calloc(1, VMZIP_DATA + bz_len + VMU_BLOCK);
	if (!buf)
		return 0;

	if (BZ2_bzBuffToBuffCompress((char*) buf + VMZIP_DATA, &bz_len, (char*) data, len, VMZIP_BZ_LEVEL, 0, VMZIP_BZ_WORK) != BZ_OK)
	{
		free(buf);
		return 0;
	}

	// as vmu_pkg_build(): descriptions space padded, app ID NUL padded
	memset(buf + VMS_DESC_VMS, ' ', 16 + 32);
	memcpy(buf + VMS_DESC_VMS, orig_name, name_len);
	memcpy(buf + VMS_DESC_DC, VMZIP_DESC_DC, strlen(VMZIP_DESC_DC));
	buf[VMS_APP_ID] = (uint8_t)(len / VMU_BLOCK);
	memcpy(buf + VMS_APP_ID + 1, VMZIP_APP_ID, strlen(VMZIP_APP_ID));
	append_le_uint16(buf + VMS_ICONS, 1);
	append_le_uint32(buf + VMS_DATA_LEN, bz_len);
	for (int i = 0; i < 16; i++)
		append_le_uint16(buf + VMS_PALETTE + i * 2, vmzip_icon_pal[i]);
	memcpy(buf + VMS_BITMAP, vmzip_icon_bmp, sizeof(vmzip_icon_bmp));

	*out_len = VMZIP_DATA + bz_len;
	if (vms_update_crc(buf, *out_len, 0) < 0)
	{
		free(buf);
		return 0;
	}

	// whole blocks, the tail zeroed (calloc)
	*out_len = (*out_len + VMU_BLOCK - 1) / VMU_BLOCK * VMU_BLOCK;
	*out = buf;
	return 1;
}

int vmzip_unpack(const uint8_t* data, size_t len, char* orig_name, uint8_t** out, size_t* out_len)
{
	vms_header_t vms;
	unsigned int dst_len;
	uint8_t* buf;
	int blocks;

	if (!vmzip_header_info(data, len, orig_name, &blocks))
		return 0;

	// the CRC isn't checked, as VMZip didn't: the bzip2 stream has its own
	if (vms_parse(data, len, 0, &vms) < 0 || vms.payload > vms.avail - vms.header_size)
		return 0;

	dst_len = blocks * VMU_BLOCK;
	buf = calloc(1, dst_len);
	if (!buf)
		return 0;

	if (BZ2_bzBuffToBuffDecompress((char*) buf, &dst_len, (char*) data + vms.header_size, vms.payload, 0, 0) != BZ_OK || !dst_len)
	{
		free(buf);
		return 0;
	}

	*out = buf;
	*out_len = blocks * VMU_BLOCK;
	return 1;
}
