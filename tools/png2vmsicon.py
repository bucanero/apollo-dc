#!/usr/bin/env python3
"""
Convert a PNG into a 32x32, 16-colour Dreamcast VMS icon, written as a C header:
a 16-entry ARGB4444 palette and a 4bpp bitmap (high nibble first).

Usage: png2vmsicon.py <input.png> <output.h> [--preview out.png]
                      [--mode fit|linework] [--threshold 0.30]

  fit       (default) scale the image to fit 32x32, keeping its aspect ratio;
            transparent pixels stay transparent (palette entry 0)
  linework  for large artwork with thin white lines on a dark background:
            an icon pixel turns white when more than `threshold` of its
            source area is white, so the lines don't average away into it

Requires Pillow.
"""
import argparse
from PIL import Image

ICON = 32


def fit(img):
    img = img.convert('RGBA')
    scale = min(ICON / img.width, ICON / img.height)
    w, h = max(1, round(img.width * scale)), max(1, round(img.height * scale))
    small = img.resize((w, h), Image.LANCZOS)
    out = Image.new('RGBA', (ICON, ICON), (0, 0, 0, 0))
    out.alpha_composite(small, ((ICON - w) // 2, (ICON - h) // 2))
    return out


def linework(img, thr):
    big = img.convert('RGB')
    mask = big.convert('L').point(lambda v: 255 if v > 150 else 0).resize((ICON, ICON), Image.BOX)
    bg = big.resize((ICON, ICON), Image.BOX)
    out = Image.new('RGBA', (ICON, ICON))
    out.putdata([(255, 255, 255, 255) if m > 255 * thr else c + (255,) for m, c in zip(mask.getdata(), bg.getdata())])
    return out


def encode(icon):
    """32x32 RGBA -> (16 ARGB4444 colours, 1024 palette indexes). Index 0 is transparent if needed."""
    px = list(icon.getdata())
    clear = [a < 128 for (_, _, _, a) in px]
    has_clear = any(clear)

    rgb = Image.new('RGB', (ICON, ICON))
    rgb.putdata([(r, g, b) for (r, g, b, _) in px])
    q = rgb.quantize(colors=15 if has_clear else 16, method=Image.MEDIANCUT, dither=Image.NONE)
    pal = (q.getpalette() or [])[:48]
    pal += [0] * (48 - len(pal))
    colours = [0xF000 | ((pal[i*3] >> 4) << 8) | ((pal[i*3+1] >> 4) << 4) | (pal[i*3+2] >> 4) for i in range(16)]
    idx = list(q.getdata())

    if has_clear:
        colours = [0x0000] + colours[:15]
        idx = [0 if c else i + 1 for c, i in zip(clear, idx)]

    return colours, idx


def write_header(path, colours, idx):
    bits = [(idx[i] << 4) | idx[i + 1] for i in range(0, ICON * ICON, 2)]
    with open(path, 'w') as f:
        f.write('// Apollo VMS icon: 32x32, 16 colours. Generated by tools/png2vmsicon.py\n')
        f.write('#ifndef APOLLO_VMU_ICON_H\n#define APOLLO_VMU_ICON_H\n\n#include <stdint.h>\n\n')
        f.write('// ARGB4444 palette\nstatic const uint16_t apollo_vmu_icon_pal[16] = {\n')
        for i in range(0, 16, 8):
            f.write('\t' + ', '.join('0x%04X' % c for c in colours[i:i+8]) + ',\n')
        f.write('};\n\n// 4 bits per pixel, high nibble first\nstatic const uint8_t apollo_vmu_icon_bmp[512] = {\n')
        for i in range(0, 512, 16):
            f.write('\t' + ', '.join('0x%02X' % b for b in bits[i:i+16]) + ',\n')
        f.write('};\n\n#endif\n')


def decode(colours, idx):
    """What the Dreamcast will draw: the ARGB4444 palette applied, as a 32x32 RGBA image."""
    out = Image.new('RGBA', (ICON, ICON))
    out.putdata([(((colours[i] >> 8) & 0xF) * 17, ((colours[i] >> 4) & 0xF) * 17,
                  (colours[i] & 0xF) * 17, ((colours[i] >> 12) & 0xF) * 17) for i in idx])
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('input')
    ap.add_argument('output')
    ap.add_argument('--preview')
    ap.add_argument('--mode', choices=['fit', 'linework'], default='fit')
    ap.add_argument('--threshold', type=float, default=0.30)
    a = ap.parse_args()

    img = Image.open(a.input)
    icon = linework(img, a.threshold) if a.mode == 'linework' else fit(img)
    colours, idx = encode(icon)
    write_header(a.output, colours, idx)

    if a.preview:
        decode(colours, idx).resize((256, 256), Image.NEAREST).save(a.preview)


if __name__ == '__main__':
    main()
